"""
FastAPI entry point for the Customer Complaint Processor.

All heavy lifting is delegated to the existing modules:
  - main.process_file()   — single file processing
  - main.run_batch()      — full data/ directory batch run
  - main.setup_directories()
"""

import os
import shutil
import asyncio
from pathlib import Path

import pandas as pd
from fastapi import FastAPI, File, UploadFile, HTTPException
from fastapi.responses import FileResponse, JSONResponse

from config import OPENAI_API_KEY, OUTPUT_DIR, STRUCTURED_DIR, SUPPORTED_FORMATS
from main import process_file, run_batch, setup_directories

app = FastAPI(
    title="Customer Complaint Processor API",
    description="LangChain + OpenAI pipeline exposed as a REST API.",
    version="1.0.0",
)


# ── Health ────────────────────────────────────────────────────────────────────

@app.get("/health", summary="Health check")
def health_check():
    if not OPENAI_API_KEY:
        raise HTTPException(status_code=503, detail="OPENAI_API_KEY is not set.")
    return {"status": "ok", "model": os.getenv("MODEL_NAME", "gpt-4o-mini")}


# ── Single file ───────────────────────────────────────────────────────────────

@app.post("/process", summary="Process a single complaint file")
async def process_single(file: UploadFile = File(...)):
    """Upload one .txt / .pdf / .docx file and get the full result as JSON."""
    suffix = Path(file.filename).suffix.lower()
    if suffix not in SUPPORTED_FORMATS:
        raise HTTPException(status_code=400, detail=f"Unsupported format: '{suffix}'")

    setup_directories()

    # Save the upload into data/ using its original name
    dest = OUTPUT_DIR.parent / "data" / file.filename
    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("wb") as f:
        shutil.copyfileobj(file.file, f)

    try:
        result = await asyncio.to_thread(process_file, dest)
        extracted = result["extracted"]
        return {
            "file_name": file.filename,
            "extracted": extracted.model_dump(),
            "customer_email": result["customer_email"],
            "case_summary": result["case_summary"],
        }
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


# ── Batch ─────────────────────────────────────────────────────────────────────

@app.post("/process/batch", summary="Process multiple complaint files")
async def process_batch(files: list[UploadFile] = File(...)):
    """Upload multiple files. Saves them to data/ then calls run_batch()."""
    setup_directories()

    # Save all uploads to data/
    data_dir = OUTPUT_DIR.parent / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    skipped = []
    for upload in files:
        suffix = Path(upload.filename).suffix.lower()
        if suffix not in SUPPORTED_FORMATS:
            skipped.append(upload.filename)
            continue
        dest = data_dir / upload.filename
        with dest.open("wb") as f:
            shutil.copyfileobj(upload.file, f)

    # Delegate entirely to run_batch()
    await asyncio.to_thread(run_batch)

    report_path = OUTPUT_DIR / "final_report.csv"
    summary = {}
    if report_path.exists():
        df = pd.read_csv(report_path)
        summary = df.to_dict(orient="records")

    return {
        "skipped": skipped,
        "results": summary,
    }


# ── Fetch saved result ────────────────────────────────────────────────────────

@app.get("/results/{stem}", summary="Fetch saved result for a complaint")
def get_result(stem: str):
    """Return the saved structured JSON for a processed complaint, e.g. complaint_001."""
    import json
    json_path = STRUCTURED_DIR / f"{stem}.json"
    if not json_path.exists():
        raise HTTPException(status_code=404, detail=f"No result found for '{stem}'.")
    return JSONResponse(content=json.loads(json_path.read_text(encoding="utf-8")))


# ── Download report ───────────────────────────────────────────────────────────

@app.get("/report", summary="Download the consolidated CSV report")
def download_report():
    """Download final_report.csv generated by the last batch run."""
    report_path = OUTPUT_DIR / "final_report.csv"
    if not report_path.exists():
        raise HTTPException(status_code=404, detail="No report yet. Run /process/batch first.")
    return FileResponse(path=str(report_path), media_type="text/csv", filename="final_report.csv")
